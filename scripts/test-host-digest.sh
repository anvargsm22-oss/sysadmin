#!/usr/bin/env bash
# test-host-digest.sh — тест переходника, приносящего дайджест состояния в подстановку.
#
# ПОЧЕМУ ТЕСТ ИМЕННО ТАКОЙ. Скрипт живёт в живой подстановке (ADR-0029), а там любая
# неудача обязана превращаться в ТЕКСТ, а не в ненулевой код: ненулевой код молча
# убивает весь ответ агента — ни ошибки, ни предупреждения, пустой вывод. Поэтому
# главная проверка каждой секции — «выход 0» — и она важнее, чем содержание вывода.
#
# Настоящего сервера тест НЕ трогает: `digest_cmd` подменяется локальной командой.
# Проверяется МОЙ код (поиск конфига, сторож времени, маскировка, коды возврата),
# а не работоспособность чужого ssh.
#
# Запуск: bash scripts/test-host-digest.sh

set -u

ROOT="$(git rev-parse --show-toplevel 2>/dev/null)" || ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SUT="$ROOT/.claude/skills/_lib/host-digest.sh"
PASS=0; FAIL=0
WORK="$(mktemp -d)"
trap 'rm -f "$WORK"/* 2>/dev/null; rmdir "$WORK" 2>/dev/null' EXIT

ok()  { PASS=$((PASS+1)); printf '  ✅ %s\n' "$1"; }
bad() { FAIL=$((FAIL+1)); printf '  ❌ %s\n' "$1"; }

# Собирает карту инфры с заданной командой дайджеста. Пустая строка = поля нет.
make_config() {  # $1 = имя файла, $2 = digest_cmd
    if [ -z "$2" ]; then
        printf '{"version":"1.0","state":{"mode":"manual"}}\n' > "$WORK/$1"
    else
        python3 - "$WORK/$1" "$2" <<'PY'
import json, sys
json.dump({"version": "1.0", "state": {"mode": "rebuild", "digest_cmd": sys.argv[2]}},
          open(sys.argv[1], "w", encoding="utf-8"), ensure_ascii=False)
PY
    fi
    echo "$WORK/$1"
}

echo "── тест переходника host-digest ────────────────────────"
echo

# ═══════════════════════════════════════════════════════════════════════════
echo "[1] Выход всегда 0 — ненулевой код убил бы ответ агента целиком"
# ═══════════════════════════════════════════════════════════════════════════
for spec in \
    "карты инфры нет вовсе|$WORK/нет-такого.json" \
    "в карте нет state.digest_cmd|$(make_config no-cmd.json "")" \
    "команда дайджеста падает|$(make_config failing.json "exit 7")" \
    "команда дайджеста не существует|$(make_config missing.json "такой-команды-нет-12345")"
do
    label="${spec%%|*}"; cfg="${spec#*|}"
    out="$(bash "$SUT" --config "$cfg" --timeout 3 2>&1)"; rc=$?
    if [ "$rc" -eq 0 ]; then ok "$label → выход 0"; else bad "$label → выход $rc (должен быть 0)"; fi
    case "$out" in
        *"НЕ СОБРАНО"*) ok "$label → сказано «НЕ СОБРАНО», агент не будет гадать" ;;
        *) bad "$label → нет слова «НЕ СОБРАНО»: $out" ;;
    esac
done
echo

# ═══════════════════════════════════════════════════════════════════════════
echo "[2] Рабочий путь: дайджест доезжает и помечен временем"
# ═══════════════════════════════════════════════════════════════════════════
printf 'контейнеров: 8\nсобран: 2026-07-27 03:30 UTC\n' > "$WORK/digest.md"
cfg="$(make_config ok.json "cat '$WORK/digest.md'")"
out="$(bash "$SUT" --config "$cfg" --timeout 5 2>&1)"; rc=$?
[ "$rc" -eq 0 ] && ok "рабочий путь → выход 0" || bad "рабочий путь → выход $rc"
case "$out" in *"контейнеров: 8"*) ok "содержимое дайджеста доехало" ;; *) bad "содержимое потерялось: $out" ;; esac
case "$out" in *"снят 20"*)         ok "проставлено время съёмки" ;;   *) bad "нет штампа времени съёмки" ;; esac
case "$out" in *"не обновляется"*)  ok "предупреждение о протухании на месте" ;; *) bad "нет предупреждения о протухании" ;; esac
echo

# ═══════════════════════════════════════════════════════════════════════════
echo "[3] Сторож времени — зависшая команда не морозит загрузку скилла"
# ═══════════════════════════════════════════════════════════════════════════
# Подстановка исполняется ДО хода агента: зависший ssh заморозил бы сессию целиком.
# Утилиты timeout на macOS нет, сторож самодельный — тем важнее его проверить.
cfg="$(make_config hang.json "sleep 30")"
started=$(date +%s)
out="$(bash "$SUT" --config "$cfg" --timeout 2 2>&1)"; rc=$?
elapsed=$(( $(date +%s) - started ))
[ "$rc" -eq 0 ] && ok "зависшая команда → выход 0" || bad "зависшая команда → выход $rc"
if [ "$elapsed" -le 8 ]; then ok "прервано за ${elapsed}с при лимите 2с"; else bad "сторож не сработал: ${elapsed}с"; fi
echo

# ═══════════════════════════════════════════════════════════════════════════
echo "[4] Секреты маскируются — вывод инструмента переживает сессию"
# ═══════════════════════════════════════════════════════════════════════════
# Правило §6.1: вывод инструмента — такой же носитель, как файл. Дайджест собирается
# на сервере, и однажды в него попадёт лишнее; маскировка обязана стоять здесь.
cfg="$(make_config secret.json "printf 'API_TOKEN=abcdef1234567890\\nвсё ок\\n'")"
out="$(bash "$SUT" --config "$cfg" --timeout 5 2>&1)"
case "$out" in
    *abcdef1234567890*) bad "секрет утёк в подстановку как есть" ;;
    *"всё ок"*)         ok "секрет замаскирован, полезный текст сохранён" ;;
    *)                  bad "вывод потерян целиком: $out" ;;
esac
echo

# ═══════════════════════════════════════════════════════════════════════════
echo "[5] Длинный дайджест обрезается — контекст не бесконечен"
# ═══════════════════════════════════════════════════════════════════════════
cfg="$(make_config long.json "seq 1 500")"
out="$(bash "$SUT" --config "$cfg" --timeout 5 --lines 10 2>&1)"
n="$(printf '%s\n' "$out" | grep -c '^[0-9]*$')"
if [ "$n" -le 12 ]; then ok "обрезано до лимита (числовых строк: $n)"; else bad "обрезка не работает: $n строк"; fi
case "$out" in *"из 500"*) ok "сказано, сколько строк скрыто" ;; *) bad "не сказано про скрытые строки" ;; esac
echo

# ═══════════════════════════════════════════════════════════════════════════
echo "[6] Строка подстановки в скилле проходит линтер переносимости"
# ═══════════════════════════════════════════════════════════════════════════
# Правило 16 (ADR-0029): страховка кода возврата обязана стоять в конце строки.
LINTER="$ROOT/scripts/check-shell-portability.sh"
if bash "$LINTER" --root "$ROOT" "$ROOT/.claude/skills/health-check/SKILL.md" >/dev/null 2>&1; then
    ok "подстановка в health-check переносима и со страховкой"
else
    bad "линтер ругается на подстановку в health-check"
fi
echo

# ═══════════════════════════════════════════════════════════════════════════
echo "[7] Находки проверщика 27.07.2026 — закрыты ли"
# ═══════════════════════════════════════════════════════════════════════════

# 7.1 Команда, игнорирующая TERM: сторож обязан добить её KILL и объявить негодной.
# Было: 25 с при лимите 3 с, и оборванный вывод отдавался как ВАЛИДНЫЙ дайджест.
cfg="$(make_config ignore-term.json "trap '' TERM; sleep 25")"
started=$(date +%s)
out="$(bash "$SUT" --config "$cfg" --timeout 2 2>&1)"; rc=$?
elapsed=$(( $(date +%s) - started ))
[ "$rc" -eq 0 ] && ok "команда, игнорирующая TERM → выход 0" || bad "выход $rc"
if [ "$elapsed" -le 10 ]; then ok "добита за ${elapsed}с при лимите 2с (эскалация до KILL работает)"
else bad "лимит не соблюдён: ${elapsed}с при лимите 2с"; fi
case "$out" in
    *"НЕ СОБРАНО"*) ok "прерванный вывод объявлен негодным, а не выдан за дайджест" ;;
    *) bad "оборванный вывод отдан как дайджест: $out" ;;
esac

# 7.2 Осиротевшие процессы. ПЕРВАЯ редакция этой проверки была фикцией: она запускала
# `echo` с лимитом 25 с — сторож не срабатывал вовсе, и считать было нечего. Проверщик
# 27.07.2026 показал, что при этом реальная сирота существовала: команда, игнорирующая
# TERM, передаёт игнорирование детям по наследству, родителя добивает KILL, а дети
# переусыновляются к init — и `pkill -P` их уже не находит. Лечение — своя группа
# процессов и убийство группы. Проверяем именно тот случай, который ломался,
# и по УНИКАЛЬНОМУ маркеру, а не по общему числу `sleep` в системе.
# Маркер обязан быть виден в argv. ВТОРАЯ редакция этой проверки была фикцией ровно
# так же, как первая, только незаметнее: маркер стоял в КОММЕНТАРИИ оболочки, до `exec`
# не доходил, `pgrep -f` не видел его никогда — и тест зеленел даже на заведомо дырявой
# версии скрипта (проверщик 27.07.2026 доказал это прогоном против старого коммита).
# Теперь маркер — уникальная длительность `sleep`, она реально попадает в argv.
SLEEP_A=40017
SLEEP_B=40019
pkill -9 -f "sleep $SLEEP_A" 2>/dev/null; pkill -9 -f "sleep $SLEEP_B" 2>/dev/null

cfg="$(make_config orphan.json "trap '' TERM; sleep $SLEEP_A")"
bash "$SUT" --config "$cfg" --timeout 2 >/dev/null 2>&1 &
probe_pid=$!
sleep 1
seen=$(pgrep -f "sleep $SLEEP_A" 2>/dev/null | wc -l | tr -d ' ')
wait "$probe_pid" 2>/dev/null
sleep 1
left=$(pgrep -f "sleep $SLEEP_A" 2>/dev/null | wc -l | tr -d ' ')
# Контроль вакуумности: если маркер не виден ВО ВРЕМЯ работы, проверка ничего не значит.
if [ "$seen" -gt 0 ]; then ok "маркер виден в argv во время работы ($seen) — проверка не вакуумна"
else bad "маркер не виден в argv: проверка сирот ничего не доказывает"; fi
if [ "$left" -eq 0 ]; then ok "сирот не осталось: команда, игнорирующая TERM, добита группой"
else bad "осталось осиротевших процессов: $left"; fi
pkill -9 -f "sleep $SLEEP_A" 2>/dev/null

# 7.2б Внук: команда порождает ребёнка, который тоже игнорирует TERM.
cfg="$(make_config orphan2.json "bash -c \"trap '' TERM; sleep $SLEEP_B\" & wait")"
bash "$SUT" --config "$cfg" --timeout 2 >/dev/null 2>&1 &
probe_pid=$!
sleep 1
seen2=$(pgrep -f "sleep $SLEEP_B" 2>/dev/null | wc -l | tr -d ' ')
wait "$probe_pid" 2>/dev/null
sleep 1
left2=$(pgrep -f "sleep $SLEEP_B" 2>/dev/null | wc -l | tr -d ' ')
if [ "$seen2" -gt 0 ]; then ok "внук виден в argv во время работы ($seen2)"
else bad "внук не виден в argv: проверка вакуумна"; fi
if [ "$left2" -eq 0 ]; then ok "внук добит вместе с группой"
else bad "внук пережил сторожа: $left2 процессов"; fi
pkill -9 -f "sleep $SLEEP_B" 2>/dev/null

# 7.3 Утечка секрета в ветке ОШИБКИ: маскировка обязана работать и там.
# Было: redact.sh подключался ПОСЛЕ этой ветки, диагностика уезжала сырой.
cfg="$(make_config errsecret.json "echo 'сбой, TOKEN=sk-ant-SEKRET99999' >&2; exit 7")"
out="$(bash "$SUT" --config "$cfg" --timeout 5 2>&1)"
case "$out" in
    *sk-ant-SEKRET99999*) bad "секрет из диагностики упавшей команды утёк сырым" ;;
    *"НЕ СОБРАНО"*)       ok "диагностика упавшей команды маскируется" ;;
    *)                    bad "неожиданный вывод: $out" ;;
esac

# 7.4 Маскировка не должна тихо отключаться при запуске из чужого каталога.
cfg="$(make_config fromelsewhere.json "printf 'API_TOKEN=abcdef1234567890\\nтело\\n'")"
out="$( cd / && bash "$SUT" --config "$cfg" --timeout 5 2>&1 )"
case "$out" in
    *abcdef1234567890*) bad "из чужого каталога маскировка отключилась молча" ;;
    *тело*)             ok "маскировка работает независимо от текущего каталога" ;;
    *)                  bad "вывод потерян: $out" ;;
esac

# 7.5 BOM в карте инфры: причина отказа должна быть верной, а не «поля нет».
printf '\xef\xbb\xbf' > "$WORK/bom.json"
python3 -c "
import json,sys
json.dump({'version':'1.0','state':{'mode':'rebuild','digest_cmd':'echo из-BOM-конфига'}},
          open(sys.argv[1],'a',encoding='utf-8'),ensure_ascii=False)" "$WORK/bom.json"
out="$(bash "$SUT" --config "$WORK/bom.json" --timeout 5 2>&1)"
case "$out" in
    *"из-BOM-конфига"*) ok "карта инфры с BOM читается" ;;
    *"не объявлено state.digest_cmd"*) bad "BOM даёт ЛОЖНУЮ причину: поле объявлено" ;;
    *) bad "неожиданный вывод на конфиге с BOM: $out" ;;
esac

# 7.6 Успешный код, пустой stdout, что-то в stderr — это предупреждение, не снимок.
cfg="$(make_config stderronly.json "echo 'сервер недоступен, показываю кэш' >&2")"
out="$(bash "$SUT" --config "$cfg" --timeout 5 2>&1)"
case "$out" in
    *"НЕ СОБРАНО"*) ok "предупреждение при пустом stdout не выдаётся за дайджест" ;;
    *) bad "предупреждение подано под шапкой дайджеста: $out" ;;
esac
echo

# ═══════════════════════════════════════════════════════════════════════════
echo "[8] Кириллица в пути и чужая кодовая страница консоли (правило 3д)"
# ═══════════════════════════════════════════════════════════════════════════
# Дефект 03.11.2026: python печатал путь к карте инфры в cp1251 (консоль Windows), профиль
# оператора — кириллицей, и скрипт объявлял живую карту «не найденной». Путь ищется только
# без --config, поэтому мозг и инфра собираются копией во временном дереве с русскими
# именами. Кодировка навязывается ИМЕННО скрипту, перекрывая наследство: так проверяется
# его собственная защита, и на Linux/macOS дефект воспроизводится так же, как на Windows.
BRAIN="$WORK/мозг агента"; INFRA="$WORK/папка инфры"
mkdir -p "$BRAIN/.claude/skills/_lib" "$INFRA"
cp "$SUT" "$ROOT/.claude/skills/_lib/redact.sh" "$BRAIN/.claude/skills/_lib/"
python3 - "$BRAIN/agent-config.json" "$INFRA" <<'PY'
import json, sys
json.dump({"projects": [{"name": "тест", "active": True, "infra_root": sys.argv[2]}]},
          open(sys.argv[1], "w", encoding="utf-8"), ensure_ascii=False)
PY
cfg="$(make_config cyr.json "echo кириллица-дошла")"; cp "$cfg" "$INFRA/infra-config.json"
out="$(env PYTHONIOENCODING=cp1251 bash "$BRAIN/.claude/skills/_lib/host-digest.sh" --timeout 5 2>&1)"
case "$out" in
    *"кириллица-дошла"*)        ok "карта инфры по кириллическому пути найдена, команда дошла целой" ;;
    *"карта инфры не найдена"*) bad "путь искажён кодировкой: $out" ;;
    *)                          bad "неожиданный вывод: $out" ;;
esac
rm -rf "$BRAIN" "$INFRA"
echo

echo "────────────────────────────────────────────────────────"
printf 'PASS: %s   FAIL: %s\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ] || exit 1
