#!/usr/bin/env bash
# host-digest.sh — приносит дайджест состояния инфры для живой подстановки в скилл.
#
# ЗАЧЕМ. Скилл диагностики может приходить уже со снимком состояния внутри вместо
# инструкции «сначала посмотри» (ADR-0029). Но команда в подстановке идёт МИМО слоя
# разрешений: ни промпта, ни зоны доверия, ни PreToolUse-хука. Поэтому серверный
# снимок берётся не произвольной командой, а ровно одной — той, что оператор сам
# объявил в своей карте инфры полем `state.digest_cmd` (ADR-0013). Хардкода адреса,
# пути и имени сервера здесь нет и быть не может (C.4).
#
# ГРАНИЦЫ. Скрипт только читает. Он не решает, что запускать, — решает конфиг
# оператора. Если поля нет, он честно печатает «НЕ СОБРАНО» и не импровизирует (C.9).
#
# ВЫХОД ВСЕГДА 0. Ненулевой код в подстановке молча убивает весь ответ агента —
# ни ошибки, ни предупреждения, пустой вывод (ожог 2026-07-27, ADR-0029, правило 16
# линтера переносимости). Поэтому любая неудача здесь превращается в текст, а не в код.
#
# Использование:
#   bash .claude/skills/_lib/host-digest.sh [--lines N] [--timeout SEC] [--config ПУТЬ]
#
# В теле скилла (обязательно со страховкой на конце):
#   !`bash "$(git rev-parse --show-toplevel)/.claude/skills/_lib/host-digest.sh" || true`

set -u
# Python здесь печатает путь к карте инфры и команду дайджеста, а консоль Windows
# отдаёт его stdout в cp1251: кириллица в пути профиля превращалась в «?», и скрипт
# объявлял карту «не найденной» при живом файле (поймано обходом 03.11.2026). Тот же
# дефект хуки уже лечат этой строкой (правило 3д).
export PYTHONIOENCODING=utf-8

LINES=60
TMO=8
CONFIG_OVERRIDE=""
# `shift 2` при одном оставшемся аргументе возвращает ошибку и НЕ сдвигает — разбор
# зацикливается навсегда. Для скрипта, который обязан всегда завершаться, это хуже
# ненулевого кода: выхода нет вовсе. Поймано проверщиком 27.07.2026 (`--lines` последним).
# Числовые значения проверяем: мусор в `--timeout` давал ложный таймаут, мусор
# в `--lines` — шапку дайджеста с пустым телом и без слова «НЕ СОБРАНО».
while [ $# -gt 0 ]; do
    case "$1" in
        --lines)   shift; case "${1:-}" in ''|*[!0-9]*) LINES=60 ;; *) LINES="$1" ;; esac; [ $# -gt 0 ] && shift ;;
        --timeout) shift; case "${1:-}" in ''|*[!0-9]*) TMO=8   ;; *) TMO="$1"   ;; esac; [ $# -gt 0 ] && shift ;;
        --config)  shift; CONFIG_OVERRIDE="${1:-}"; [ $# -gt 0 ] && shift ;;
        -h|--help) sed -n '2,26p' "$0"; exit 0 ;;
        *) shift ;;
    esac
done
[ "$LINES" -gt 0 ] 2>/dev/null || LINES=60
[ "$TMO"   -gt 0 ] 2>/dev/null || TMO=8

# Корень берём от РАСПОЛОЖЕНИЯ скрипта, а не от текущего каталога. Прежняя версия
# считала его через `git rev-parse` от cwd: при запуске из чужого каталога рядом не
# находился `redact.sh`, и маскировка секретов молча отключалась — без единого слова
# в выводе (проверщик 27.07.2026). Тихо снятая защита хуже отсутствующей.
SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SELF_DIR/../../.." && pwd)"

# Печатает причину, по которой снимка нет, и как получить то же руками.
# Гадать по отсутствующему снимку агенту запрещено — он обязан увидеть слово НЕ СОБРАНО.
not_collected() {
    printf 'НЕ СОБРАНО: %s\n' "$1"
    printf 'Как получить вручную: %s\n' "${2:-открой карту инфры и выполни state.digest_cmd сам}"
    exit 0
}

# ─── 1. Находим карту инфры активного проекта ────────────────────────────────
if [ -n "$CONFIG_OVERRIDE" ]; then
    INFRA_CONFIG="$CONFIG_OVERRIDE"
else
    AGENT_CONFIG="$ROOT/agent-config.json"
    [ -f "$AGENT_CONFIG" ] || not_collected \
        "мозг агента не настроен (нет $AGENT_CONFIG)" "запусти /sysadmin-init"

    command -v python3 >/dev/null 2>&1 || not_collected \
        "на машине нет python3 — разобрать конфиг нечем" \
        "прочитай state.digest_cmd из карты инфры глазами и выполни сам"

    INFRA_CONFIG="$(python3 - "$AGENT_CONFIG" <<'PY' 2>/dev/null
import json, os, sys
try:
    cfg = json.load(open(sys.argv[1], encoding="utf-8-sig"))
except Exception:
    sys.exit(0)
projects = cfg.get("projects") or []
# Активный проект: помеченный active, иначе единственный. Двусмысленность — не угадываем.
active = [p for p in projects if p.get("active")] or (projects if len(projects) == 1 else [])
if len(active) != 1:
    sys.exit(0)
root = (active[0].get("infra_root") or "").strip()
if not root:
    sys.exit(0)
# Относительный путь резолвится от каталога конфига — канон ADR-0008.
if not os.path.isabs(root):
    root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(sys.argv[1])), root))
print(os.path.join(root, "infra-config.json"))
PY
)"
    [ -n "$INFRA_CONFIG" ] || not_collected \
        "в мозге не найден один активный проект с infra_root" "запусти /sysadmin-init --reconfigure"
fi

[ -f "$INFRA_CONFIG" ] || not_collected \
    "карта инфры не найдена ($INFRA_CONFIG)" "запусти /sysadmin-init"

# ─── 2. Берём команду дайджеста из паспорта состояния ────────────────────────
DIGEST_CMD="$(python3 - "$INFRA_CONFIG" <<'PY' 2>/dev/null
import json, sys
try:
    cfg = json.load(open(sys.argv[1], encoding="utf-8-sig"))
except Exception:
    sys.exit(0)
print(((cfg.get("state") or {}).get("digest_cmd") or "").strip())
PY
)"

if [ -z "$DIGEST_CMD" ]; then
    # Отличаем «поля нет» от «файл битый или закрыт правами»: раньше оба случая давали
    # одну причину, и оператора отправляли перенастраивать конфиг вместо починки файла.
    if ! python3 -c 'import json,sys; json.load(open(sys.argv[1],encoding="utf-8-sig"))' "$INFRA_CONFIG" 2>/dev/null; then
        [ -r "$INFRA_CONFIG" ] || not_collected \
            "карта инфры не читается (нет прав): $INFRA_CONFIG" "проверь права на файл"
        not_collected "карта инфры повреждена — не разбирается как JSON: $INFRA_CONFIG" \
            "почини файл; структуру создаёт /sysadmin-init"
    fi
    not_collected "в карте инфры не объявлено state.digest_cmd" \
        "объяви его через /sysadmin-init --reconfigure либо собери состояние скиллом /inventory-scan"
fi

# ─── 3. Выполняем — с ограничением по времени ────────────────────────────────
# Сторож нужен, потому что подстановка исполняется ДО того, как агент начнёт ход:
# зависший ssh к недоступному серверу заморозил бы загрузку скилла целиком.
# Утилиты `timeout` на macOS нет (проверено), поэтому сторож свой.
#
# Первая редакция сторожа слала TERM ОДИН раз и не эскалировала. Проверщик 27.07.2026
# показал цену: команда, игнорирующая TERM, отработала 25 с при лимите 3 с — та самая
# заморозка, ради которой сторож писался, — и её просроченный вывод был отдан как
# ВАЛИДНЫЙ дайджест, без единого слова про переработку. Плюс за собой сторож оставлял
# осиротевшие процессы. Теперь: TERM → пауза → KILL, добивание детей обеих сторон,
# и факт срабатывания фиксируется меткой — по ней вывод объявляется негодным.
OUT_FILE="$(mktemp)"; ERR_FILE="$(mktemp)"; TMO_MARK="$(mktemp)"
trap 'rm -f "$OUT_FILE" "$ERR_FILE" "$TMO_MARK" 2>/dev/null' EXIT

# Маскировка подключается ДО запуска команды: в первой редакции она стояла ниже ветки
# ошибки, и диагностика упавшей команды уезжала в транскрипт СЫРОЙ. Падающие ssh/curl/psql
# регулярно эхоят креды в тексте ошибки (§6.1: вывод инструмента — такой же носитель).
REDACT_OK=0
if [ -f "$SELF_DIR/redact.sh" ]; then
    # shellcheck disable=SC1091
    . "$SELF_DIR/redact.sh" 2>/dev/null && command -v redact_stream >/dev/null 2>&1 && REDACT_OK=1
fi
# Тихо снятая защита хуже отсутствующей — это записано в шапке файла, но до сих пор
# не выполнялось: без `redact.sh` рядом (или при битом файле) маскировка молча
# превращалась в `cat`, и секреты уходили сырыми. Проверщик 27.07.2026 показал четыре
# утечки. Теперь отсутствие защиты — повод отказаться от печати, а не работать вслепую.
mask() { if [ "$REDACT_OK" -eq 1 ]; then redact_stream; else cat; fi; }
if [ "$REDACT_OK" -eq 0 ]; then
    printf 'НЕ СОБРАНО: библиотека маскировки секретов (_lib/redact.sh) не найдена или не читается\n'
    printf 'Печатать вывод сервера без маскировки нельзя: транскрипт переживает сессию (§6.1)\n'
    printf 'Как получить вручную: выполни state.digest_cmd сам\n'
    exit 0
fi

# Запускаем команду в СОБСТВЕННОЙ группе процессов (`set -m` включает управление
# заданиями, и фоновое задание получает свой pgid). Иначе добить её потомков нельзя:
# игнорирование сигнала НАСЛЕДУЕТСЯ детьми через fork, `pkill -P` шлёт им TERM, они его
# игнорируют, родителя через паузу убивает KILL — и дети переусыновляются к init, после
# чего `pkill -P` уже никого не находит. Проверщик 27.07.2026 воспроизвёл это на штатной
# фикстуре теста: после выхода скрипта оставался `sleep` с PPID 1. Убийство ГРУППЫ
# (отрицательный PID) достаёт и переусыновлённых.
set -m
eval "$DIGEST_CMD" >"$OUT_FILE" 2>"$ERR_FILE" &
CMD_PID=$!
set +m
(
    sleep "$TMO"
    # Проверяем, жива ли ещё команда, ПРЕЖДЕ чем объявлять таймаут. Без этой проверки
    # сторож лгал: снимая его после успешного прогона, мы убиваем его `sleep`, subshell
    # просыпается досрочно и честно помечает таймаут — для команды, которая отработала
    # мгновенно. Тест поймал это сразу: `printf` объявлялся «не уложившимся в 5 с».
    kill -0 "$CMD_PID" 2>/dev/null || exit 0
    printf 'timeout\n' > "$TMO_MARK"
    kill -TERM -"$CMD_PID" 2>/dev/null || kill -TERM "$CMD_PID" 2>/dev/null
    sleep 2
    kill -KILL -"$CMD_PID" 2>/dev/null || kill -KILL "$CMD_PID" 2>/dev/null
) >/dev/null 2>&1 &
WATCH_PID=$!
wait "$CMD_PID" 2>/dev/null
RC=$?
# Сторожа и его собственный sleep снимаем оба: иначе на каждую загрузку скилла
# оставался жить лишний процесс на весь лимит («после себя убираю», §3.10).
# Снятие сторожа глушим целиком: оболочка печатает job-notification со ВСЕМ телом
# сторожа в stderr, а stderr подстановки уезжает в тело скилла. Агент при каждой
# загрузке получал «Terminated: 15» и текст с `kill -KILL` — читается как сбой.
# Регрессия внесена коммитом 68fe3f4 и поймана проверщиком в тот же день.
{ kill "$WATCH_PID" 2>/dev/null; pkill -P "$WATCH_PID" 2>/dev/null; wait "$WATCH_PID" 2>/dev/null; } 2>/dev/null
# Подстраховка: если команда всё-таки пережила сторожа, группу добиваем здесь.
{ kill -KILL -"$CMD_PID" 2>/dev/null; } 2>/dev/null

FETCHED="$(date '+%Y-%m-%d %H:%M')"

# Сработал сторож — дайджеста нет, каким бы полным ни выглядел вывод: он оборван
# на середине, и отдавать обрывок за снимок состояния значит выдумывать данные (C.2).
if [ -s "$TMO_MARK" ]; then
    printf 'НЕ СОБРАНО: команда дайджеста не уложилась в %sс и была прервана\n' "$TMO"
    printf 'Команда (из карты инфры): %s\n' "$DIGEST_CMD" | mask
    printf 'Вывод оборван на середине и потому не показан.\n'
    printf 'Как получить вручную: выполни команду сам — вероятно, сервер недоступен\n'
    exit 0
fi

# Ненулевой код = дайджеста нет, ЧТО БЫ ни лежало в выводе. Тест поймал ровно этот
# случай: несуществующая команда пишет «command not found» в тот же поток, вывод
# оказывается непустым — и сообщение об ошибке уезжает агенту под видом снимка
# состояния. Ошибка, выданная за данные, хуже отсутствия данных (C.2).
if [ "$RC" -ne 0 ]; then
    printf 'НЕ СОБРАНО: команда дайджеста вернула код %s (лимит %sс)\n' "$RC" "$TMO"
    printf 'Команда (из карты инфры): %s\n' "$DIGEST_CMD" | mask
    if [ -s "$ERR_FILE" ] || [ -s "$OUT_FILE" ]; then
        printf 'Что она сказала (это НЕ дайджест, а диагностика):\n'
        cat "$ERR_FILE" "$OUT_FILE" 2>/dev/null | head -n 5 | mask
    fi
    printf 'Как получить вручную: выполни команду сам и посмотри на ошибку\n'
    exit 0
fi

# Код нулевой, но на stdout пусто, а в stderr что-то есть — это предупреждение,
# а не снимок. Остаток класса «ошибка под видом данных»: команда отработала успешно
# и написала «сервер недоступен, показываю кэш» — под шапкой «ДАЙДЖЕСТ СОСТОЯНИЯ»
# это читалось бы как факт о сервере.
if [ ! -s "$OUT_FILE" ]; then
    printf 'НЕ СОБРАНО: команда отработала успешно, но дайджеста не выдала\n'
    printf 'Команда (из карты инфры): %s\n' "$DIGEST_CMD" | mask
    if [ -s "$ERR_FILE" ]; then
        printf 'Что она сказала (это НЕ дайджест, а диагностика):\n'
        head -n 5 < "$ERR_FILE" | mask
    fi
    printf 'Как получить вручную: выполни команду сам\n'
    exit 0
fi

# ─── 4. Печать снимка ────────────────────────────────────────────────────────
printf 'ДАЙДЖЕСТ СОСТОЯНИЯ ИНФРЫ — снят %s, командой из карты инфры\n' "$FETCHED"
printf 'Снимок сделан ОДИН раз при загрузке скилла и дальше не обновляется.\n'
printf 'Дата СБОРКИ дайджеста на сервере — внутри него самого; переходник её не\n'
printf 'извлекает и не гарантирует. Не нашлась — так и скажи оператору (§4.6).\n'
printf -- '---\n'

# Потолок по байтам, а не только по строкам: вывод в 40 МБ ОДНОЙ строкой проходил
# `head -n` целиком и уезжал в контекст (проверщик 27.07.2026). Контекст исчерпаем.
MAXBYTES=100000
mask < "$OUT_FILE" | head -n "$LINES" | head -c "$MAXBYTES"

TOTAL="$(wc -l < "$OUT_FILE" | tr -d ' ')"
if [ "$TOTAL" -gt "$LINES" ]; then
    printf -- '--- показано %s строк из %s; остальное — точечно из полного снимка ---\n' "$LINES" "$TOTAL"
fi

exit 0
